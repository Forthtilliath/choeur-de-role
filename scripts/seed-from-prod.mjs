/**
 * Dumps production public data into supabase/seeds/prod-data.sql.
 * Auth users are excluded — only public.* tables are exported.
 * The FK members.id → auth.users.id is bypassed with session_replication_role.
 *
 * Usage:
 *   npm run db:seed-from-prod
 *
 * Then apply locally:
 *   npx supabase db reset
 *   npm run e2e:setup
 */
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

const OUT = path.resolve('supabase/seeds/prod-data.sql');

// Tables to exclude from the dump (too large or irrelevant for local testing)
const EXCLUDE = ['audit_log'];

const excludeArgs = EXCLUDE.map((t) => `-x public.${t}`).join(' ');

console.log('Connexion à la prod et dump en cours...');
console.log('(peut prendre quelques secondes)\n');

try {
  const sql = execSync(
    `npx supabase db dump --linked --data-only --schema public ${excludeArgs}`,
    { encoding: 'utf-8', maxBuffer: 50 * 1024 * 1024 },
  );

  const wrapped = [
    '-- Production data seed (public schema only, no auth users)',
    '-- Generated by scripts/seed-from-prod.mjs',
    `-- ${new Date().toISOString()}`,
    '',
    '-- Disable FK checks so members rows can exist without auth.users counterparts',
    'SET session_replication_role = replica;',
    '',
    '-- Truncate all public tables to avoid conflicts with data inserted by migrations',
    'DO $$ DECLARE r RECORD; BEGIN',
    '  FOR r IN (SELECT tablename FROM pg_tables WHERE schemaname = \'public\') LOOP',
    '    EXECUTE \'TRUNCATE TABLE public.\' || quote_ident(r.tablename) || \' CASCADE\';',
    '  END LOOP;',
    'END $$;',
    '',
    sql,
    '',
    'SET session_replication_role = DEFAULT;',
  ].join('\n');

  fs.writeFileSync(OUT, wrapped, 'utf8');
  console.log(`✅ Dump écrit dans ${OUT}`);
  console.log(`   Taille : ${(fs.statSync(OUT).size / 1024).toFixed(0)} Ko\n`);
  console.log('Étapes suivantes :');
  console.log('  npx supabase db reset   ← applique migrations + seed');
  console.log('  npm run e2e:setup       ← recrée les comptes de test');
} catch (err) {
  console.error('Erreur lors du dump :', err.message);
  process.exit(1);
}
